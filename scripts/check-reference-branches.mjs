#!/usr/bin/env node
// scripts/check-reference-branches.mjs
// Per audit doc §8.4 and exec doc §10.4 — classify each reference / retrieval
// branch into: already-contained / selective-cherry-pick / superseded /
// archive-only / blocked-from-merge. Outputs a markdown report.

import { execSync } from 'node:child_process';

const TARGETS = [
  // already-contained candidates (per audit doc §8.4)
  'feature/visual-upgrade-engine-v1',
  'feature/image-generation-deliverables',
  'feature/image-generation-v1',
  'feature/image-generation-multi-source',
  // other reference / retrieval branches
  'feature/image-generation-creative-director',
  'feature/reference-anchor-workflow',
  'feature/reference-led-visual-direction',
  'feature/visual-context-contract',
  'refactor/repository-slimming-v2',
  'feature/document-context-extractor',
  'feature/reference-asset-selection-protocol',
];

function sh(cmd) {
  try {
    return execSync(cmd, { encoding: 'utf8' }).trim();
  } catch (err) {
    return err.stdout?.toString().trim() || err.message;
  }
}

function isAncestor(branch) {
  try {
    execSync(`git merge-base --is-ancestor origin/${branch} HEAD`, { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function diffStat(branch) {
  return sh(`git diff --shortstat HEAD...origin/${branch}`);
}

function cherry(branch) {
  return sh(`git cherry HEAD origin/${branch} 2>&1`).split('\n').slice(0, 10).join('\n');
}

function cherryCount(branch) {
  const out = sh(`git cherry HEAD origin/${branch} 2>&1`);
  const lines = out.split('\n').filter((l) => l.trim().length > 0);
  return { total: lines.length, plus: lines.filter((l) => l.startsWith('+')).length, minus: lines.filter((l) => l.startsWith('-')).length };
}

function branchCommit(branch) {
  return sh(`git rev-parse --short origin/${branch}`);
}

function branchExists(branch) {
  try {
    execSync(`git show-ref --verify --quiet refs/remotes/origin/${branch}`, { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function classify(branch) {
  if (!branchExists(branch)) {
    return { state: 'remote-gone', classification: 'archive-only' };
  }
  if (isAncestor(branch)) {
    return { state: 'contained', classification: 'already-contained' };
  }
  const c = cherryCount(branch);
  if (c.plus === 0) {
    return { state: 'not-in-head', classification: 'superseded' };
  }
  if (c.plus < 10) {
    return { state: 'not-in-head', classification: 'selective-cherry-pick' };
  }
  return { state: 'not-in-head', classification: 'archive-only' };
}

const rows = TARGETS.map((branch) => {
  const { state, classification } = classify(branch);
  if (state === 'remote-gone') {
    return { branch, state, classification, commit: '—', cherryPlus: '—', cherryMinus: '—', diffStat: '—' };
  }
  const c = cherryCount(branch);
  return {
    branch,
    state,
    classification,
    commit: branchCommit(branch),
    cherryPlus: c.plus,
    cherryMinus: c.minus,
    diffStat: diffStat(branch),
  };
});

const lines = [];
lines.push('# Reference / retrieval branch disposition');
lines.push('');
lines.push('Generated by `node scripts/check-reference-branches.mjs`. HEAD = `' + sh('git rev-parse --short HEAD') + '` (chore/repository-consolidation-5.0).');
lines.push('');
lines.push('Classifications (per audit doc §8.4 and exec doc §10.4):');
lines.push('');
lines.push('- **already-contained** — `git merge-base --is-ancestor origin/branch HEAD` is true; the branch is part of the consolidation result and can be deleted.');
lines.push('- **selective-cherry-pick** — small number of `+` commits; consider individually importing the remaining value.');
lines.push('- **superseded** — all cherry entries are `-`; the branch has no commits that are not in HEAD.');
lines.push('- **archive-only** — large divergence or remote-gone; keep the remote as a read-only historical record, never merge.');
lines.push('');
lines.push('| Branch | Remote | Classification | HEAD short | `+` cherry | `-` cherry | diffstat |');
lines.push('|---|---|---|---|---:|---:|---|');
for (const r of rows) {
  lines.push(`| \`${r.branch}\` | ${r.state} | **${r.classification}** | \`${r.commit}\` | ${r.cherryPlus} | ${r.cherryMinus} | ${r.diffStat} |`);
}
lines.push('');
lines.push('## Per-branch notes');
lines.push('');
for (const r of rows) {
  lines.push(`### \`${r.branch}\``);
  lines.push('');
  lines.push(`- State: **${r.state}**`);
  lines.push(`- Classification: **${r.classification}**`);
  if (r.state === 'not-in-head') {
    lines.push(`- Cherry (HEAD vs origin): +${r.cherryPlus} / -${r.cherryMinus}`);
    lines.push(`- Diffstat: \`${r.diffStat}\``);
    lines.push('');
    lines.push('Top `git cherry` lines:');
    lines.push('');
    lines.push('```');
    lines.push(cherry(r.branch) || '(none)');
    lines.push('```');
  }
  lines.push('');
}
lines.push('## Action plan');
lines.push('');
lines.push('1. After the consolidation PR merges, delete the local + remote branches tagged **already-contained** in the table above.');
lines.push('2. For **selective-cherry-pick** branches, open individual PRs per valuable commit; never merge the whole branch.');
lines.push('3. **superseded** branches are deleted without further action.');
lines.push('4. **archive-only** branches stay as read-only references; tag them with `archive/<branch>-<date>` if not already tagged.');

process.stdout.write(lines.join('\n') + '\n');
